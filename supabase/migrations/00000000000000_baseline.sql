 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
begin
  if coalesce(new.raw_app_meta_data->>'kind', '') = 'owner'
     or lower(coalesce(new.email, '')) like '%@owner.invalid' then
    return new;
  end if;
  insert into public.admin_users (id, email, google_name, role)
  values (
    new.id,
    coalesce(new.email, ''),
    coalesce(new.raw_user_meta_data->>'full_name', new.raw_user_meta_data->>'name'),
    case when lower(coalesce(new.email,'')) = 'tareura@gmail.com' then 'owner'::public.admin_role else 'pending'::public.admin_role end
  )
  on conflict (id) do nothing;
  return new;
end
$function$;

