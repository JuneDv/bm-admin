CREATE OR REPLACE FUNCTION public.push_recipients(p_message_id bigint)
 RETURNS TABLE(user_id uuid, sub_id bigint, endpoint text, p256dh text, auth text)
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  with m as (select * from public.site_messages where id = p_message_id),
  s as (select s.* from public.sites s join m on s.bm_key = m.bm_key),
  roles as (
    select unnest(case when m.target_role is not null then array[m.target_role]
                       else public.chat_active_roles(m.bm_key) end) as r
    from m
  ),
  names as (
    select distinct nullif(trim(case roles.r when '영업' then s.manager when '설계' then s.designer when '인테리어' then s.interior end), '') as nm
    from roles, s
  ),
  users as (
    select a.id
    from public.admin_users a
    join names on trim(coalesce(a.staff_name, '')) = names.nm
    where names.nm is not null
      and a.role in ('manager','owner','admin','gongmu','pm','master')
      and a.id is distinct from (select user_id from m)
      and ((select target_role from m) is not null
           or coalesce((select p.messages from public.notification_prefs p where p.user_id = a.id), true))
    union
    select a.id
    from public.admin_users a, m
    where ((m.target_role = '공무' and a.role = 'gongmu') or (m.target_role = 'PM' and a.role = 'pm'))
      and a.id is distinct from m.user_id
    union
    -- 건축주톡: 그 현장에 연결된 건축주 (공간 Talk가 열려 있을 때만)
    select os.user_id
    from public.owner_sites os
    join m on m.bm_key = os.bm_key and m.channel = 'owner'
    join public.owner_talk_sites t on t.bm_key = os.bm_key
    where os.user_id is distinct from m.user_id
  )
  select ps.user_id, ps.id, ps.endpoint, ps.p256dh, ps.auth
  from public.push_subscriptions ps
  join users u on u.id = ps.user_id
$function$;
revoke execute on function public.push_recipients(p_message_id bigint) from public, anon, authenticated;

CREATE OR REPLACE FUNCTION public.digest_pending()
 RETURNS TABLE(user_id uuid, n bigint, sites bigint, calls bigint)
 LANGUAGE sql
