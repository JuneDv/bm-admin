CREATE OR REPLACE FUNCTION public.finalize_sync(p_run_at timestamp with time zone)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare v_archived int; v_restored int; v_items int; v_purged int;
begin
  update public.sites set archived_at = now() where synced_at < p_run_at and archived_at is null;
  get diagnostics v_archived = row_count;
  update public.sites set archived_at = null where synced_at >= p_run_at and archived_at is not null;
  get diagnostics v_restored = row_count;
  delete from public.stage_items si where si.synced_at < p_run_at
    and exists (select 1 from public.sites s where s.bm_key = si.bm_key and s.archived_at is null);
  get diagnostics v_items = row_count;
  delete from public.sites where archived_at < now() - interval '5 years';
  get diagnostics v_purged = row_count;
  return jsonb_build_object('archived', v_archived, 'restored', v_restored, 'stale_items_deleted', v_items, 'purged_5y', v_purged);
end $function$;
revoke execute on function public.finalize_sync(p_run_at timestamp with time zone) from public, anon, authenticated;

CREATE OR REPLACE FUNCTION public.norm_phones(p text[])
 RETURNS text[]
 LANGUAGE sql
 IMMUTABLE
AS $function$
  select coalesce(array_agg(x order by ord), '{}'::text[]) from (
    select x, min(ord) ord from (
      select raw.ord, parts.x from (
        select regexp_replace(coalesce(v, ''), '[^0-9]', '', 'g') d, ord from unnest(p) with ordinality u(v, ord)
      ) raw
      cross join lateral (
        select unnest(case
          when length(raw.d) > 11 and raw.d ~ '^(01\d{9})+$' then regexp_split_to_array(regexp_replace(raw.d, '(01\d{9})', '\1,', 'g'), ',')   -- 11자리 휴대폰이 이어 붙음
          when length(raw.d) > 10 and raw.d ~ '^(01\d{8})+$' then regexp_split_to_array(regexp_replace(raw.d, '(01\d{8})', '\1,', 'g'), ',')   -- 10자리(011 등)가 이어 붙음
          else array[raw.d] end) as x
      ) parts
      where parts.x <> ''
    ) s
    group by x
  ) t
$function$;

